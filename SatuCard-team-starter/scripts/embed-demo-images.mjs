import { readFileSync, writeFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';

// Run after changing a demo photo. Separate bundles keep each added file small.
const root = new URL('../', import.meta.url), context = { window: {} };
runInNewContext(readFileSync(new URL('product-samples.js', root), 'utf8'), context);
const inline = key => 'data:image/jpeg;base64,' + readFileSync(new URL(`assets/images/${key}.jpg`, root)).toString('base64');
const original = ['headphones', 'sneaker', 'skincare'];
const initial = '{' + original.map(key => JSON.stringify(key) + ': ' + JSON.stringify(inline(key))).join(', ') + '}';
writeFileSync(new URL('assets/demo-images.js', root), '// Embedded demo photos allow PNG export even when opened via file://.\r\nwindow.SATUCARD_DEMO_IMAGES = ' + initial + ';\r\n');
for (const key of Object.keys(context.window.SATUCARD_SAMPLES).filter(key => !original.includes(key))) {
  writeFileSync(new URL(`assets/demo-${key}.js`, root), `// Embedded ${key} photo for local file export. Generated by scripts/embed-demo-images.mjs.\nwindow.SATUCARD_DEMO_IMAGES.${key} = ` + JSON.stringify(inline(key)) + ';\n');
}
